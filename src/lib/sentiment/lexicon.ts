/**
 * 获取词汇的情感强度
 */
export function getSentimentIntensity(word: string): {
    sentiment: 'positive' | 'negative' | 'neutral';
    intensity: number;
} {
    if (SENTIMENT_LEXICON.positive[word]) {
        return {
            sentiment: 'positive',
            intensity: SENTIMENT_LEXICON.positive[word]
        };
    }
    
    if (SENTIMENT_LEXICON.negative[word]) {
        return {
            sentiment: 'negative',
            intensity: SENTIMENT_LEXICON.negative[word]
        };
    }
    
    return {
        sentiment: 'neutral',
        intensity: 0.1
    };
}

/**
 * 获取词汇的特殊类型
 */
export function getSpecialType(word: string): string | undefined {
    for (const [type, keywords] of Object.entries(SENTIMENT_LEXICON.special)) {
        if (keywords.includes(word)) {
            return type;
        }
    }
    return undefined;
}

/**
 * 批量分析词汇情感
 */
export function analyzeBatch(words: string[]): Array<{
    text: string;
    sentiment: 'positive' | 'negative' | 'neutral';
    intensity: number;
    specialType?: string;
}> {
    return words.map(word => {
        const { sentiment, intensity } = getSentimentIntensity(word);
        const specialType = getSpecialType(word);
        
        return {
            text: word,
            sentiment,
            intensity,
            specialType
        };
    });
}